def validate_config():
    """验证配置参数的有效性"""
    errors = []

    # 检查超时配置
    if WAKE_WORD_TIMEOUT <= 0:
        errors.append("WAKE_WORD_TIMEOUT 必须大于 0")
    
    if DIALOG_TIMEOUT <= 0:
        errors.append("DIALOG_TIMEOUT 必须大于 0")
    
    if COMMAND_TIMEOUT <= 0:
        errors.append("COMMAND_TIMEOUT 必须大于 0")

    # 检查 TTS 配置
    if not (0.0 <= TTS_VOLUME <= 1.0):
        errors.append("TTS_VOLUME 必须在 0.0 到 1.0 之间")
    
    if not (80 <= TTS_RATE <= 300):
        errors.append("TTS_RATE 建议在 80 到 300 之间")

    # 检查唤醒词
    if not WAKE_WORDS:
        errors.append("WAKE_WORDS 不能为空")

    # 检查意图模式
    if not INTENT_PATTERNS:
        errors.append("INTENT_PATTERNS 不能为空")

    if errors:
        print("❌ 配置验证失败：")
        for error in errors:
            print(f"  - {error}")
        return False
    
    print("✅ 配置验证通过")
    return True


